"""숫자 굴리기 — 족보 400개 정의.

족보 하나 = H(...) 한 줄.
  key   : 영문 열쇠 (엔진·검증에서 씀)
  name  : 도감에 보이는 이름
  rule  : 한 줄 규칙 (예시 포함)
  fam   : 계열 (same/stair/mirror/kind/pos/math/word/combo)
  raw   : 기준 구현(C 식). 같은 묶음(grp)의 더 높은 족보가 걸리면 낮은 것은 안 걸린다.
  mk    : 빛나는 자리(C 식, 9비트)
  grp   : 묶음 이름. 같은 묶음 안에서는 뒤에 적힌 것이 더 높다 (가장 높은 것 하나만 인정).
  fl    : 도감에 보이는 한 줄 농담 (없어도 됨)
  tag   : 모음집 이름 (도전과제용)
"""

HANDS = []
_keys = set()

FAMS = {
    'same': '같은 숫자', 'stair': '오르내림', 'mirror': '대칭·반복', 'kind': '숫자 종류',
    'pos': '자리', 'math': '산수·키패드', 'word': '숫자 말장난', 'combo': '합체',
}


def H(key, name, rule, fam, raw, mk, grp=None, fl=None, tag=None, eng=None):
    assert key not in _keys, key
    assert fam in FAMS, fam
    _keys.add(key)
    HANDS.append(dict(key=key, name=name, rule=rule, fam=fam, raw=raw, mk=mk, grp=grp, fl=fl, tag=tag, eng=eng))


def ro(s):
    """'~로/으로' 조사 (끝 숫자 기준)"""
    return '으로' if s[-1] in '036' else '로'


def W(key, name, strs, note=None, fl=None, tag=None, grp=None, fam='word', rule=None):
    """숫자 속에 strs 중 하나가 들어 있음"""
    if isinstance(strs, str):
        strs = [strs]
    lst = '|'.join(strs)
    if rule is None:
        rule = '숫자 속에 ' + ', '.join(strs)
        if note:
            rule += ' (%s)' % note
    H(key, name, rule, fam, 'HAS("%s")' % lst, 'MHAS("%s")' % lst, grp=grp, fl=fl, tag=tag, eng=('frag', strs))


def S(key, name, s, note=None, fl=None, tag=None, grp=None, fam='pos'):
    rule = '%s%s 시작' % (s, ro(s))
    if note:
        rule += ' (%s)' % note
    H(key, name, rule, fam, 'STARTS("%s")' % s, 'span(0,%d)' % len(s), grp=grp, fl=fl, tag=tag, eng=('start', s))


def E(key, name, s, note=None, fl=None, tag=None, grp=None, fam='pos'):
    rule = '%s%s 끝남' % (s, ro(s))
    if note:
        rule += ' (%s)' % note
    H(key, name, rule, fam, 'ENDS("%s")' % s, 'span(%d,%d)' % (9 - len(s), len(s)), grp=grp, fl=fl, tag=tag, eng=('end', s))


def K(key, name, parts, rule, fl=None, tag=None):
    """합체: parts(조각들)가 한 숫자에 전부"""
    raw = ' && '.join('HAS("%s")' % p for p in parts)
    mk = ' | '.join('MHAS("%s")' % p for p in parts)
    H(key, name, rule, 'combo', raw, mk, fl=fl, tag=tag, eng=('all', parts))


def T(key, name, s, rule, fl=None, tag=None, grp=None, fam='combo'):
    """같은 조각이 2번 (안 겹치게)"""
    H(key, name, rule, fam, 'OCC("%s")>=2' % s, 'MALL("%s")' % s, grp=grp, fl=fl, tag=tag, eng=('twice', s))


def upside(word):
    """계산기를 뒤집으면 word로 읽히는 숫자열"""
    m = {'O': '0', 'I': '1', 'Z': '2', 'E': '3', 'H': '4', 'S': '5', 'G': '6', 'L': '7', 'B': '8', 'g': '9'}
    return ''.join(m[ch] for ch in reversed(word))


def CALC(key, name, word, show, fl=None, grp=None):
    s = upside(word)
    W(key, name, s, '계산기를 뒤집으면 %s' % show, fl=fl, tag='calc', grp=grp)


